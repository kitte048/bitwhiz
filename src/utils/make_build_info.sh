#!/bin/sh
#**********************************************************************#
#  Write src/modules/build_mod.f95: WHEN and FROM WHICH git version    #
#  bitwhiz was built. The Makefile runs this on every 'make'; the      #
#  banner and the heartbeat print what it records.                     #
#                                                                      #
#  The output file is generated, so it is in .gitignore. Never edit    #
#  it by hand; edit this script instead.                               #
#                                                                      #
#  Usage:  sh src/utils/make_build_info.sh [output file]               #
#**********************************************************************#
out=${1:-src/modules/build_mod.f95}

# When: local date, time and time zone of the build, e.g.
#    2026-10-13 21:41:07 -0400
when=$(date '+%Y-%m-%d %H:%M:%S %z')

# What: the nearest git tag, commits since it, and the commit hash, plus
# "-dirty" if tracked files have uncommitted changes, e.g.
#    v0.3-12-g9f2c1ab-dirty
# --no-optional-locks makes git only READ its index, never rewrite it.
# A release exported by export_nanohub.sh carries a VERSION file with
# its tag (e.g. v1.0.3), and that wins: on nanoHUB the folder is not
# this repository's checkout (or is the tool's own, whose tags are
# not ours). Outside a git checkout and without VERSION (e.g. a
# student's tarball) this is "unknown".
if [ -s VERSION ]; then
   what=$(head -1 VERSION | tr -d ' \r\n')
else
   what=$(git --no-optional-locks describe --tags --always --dirty 2>/dev/null)
fi
[ -n "$what" ] || what=unknown

cat > "$out" <<EOF_FORTRAN
module build
!**********************************************************************!
!
!  GENERATED by src/utils/make_build_info.sh on every 'make'.
!  Do not edit; it is not kept in git.
!
!  Purpose:
!    When, and from which git version, this executable was built.
!    These are functions, not parameters, so a new build date does
!    not force the files that use this module to recompile.
!
!**********************************************************************!
implicit none
private
public :: build_date, build_version
contains

   function build_date() result(s)
   character(len=:), allocatable :: s
   s = '$when'
   end function build_date

   function build_version() result(s)
   character(len=:), allocatable :: s
   s = '$what'
   end function build_version

end module build
EOF_FORTRAN
